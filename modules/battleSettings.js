function checkbox(checked, onChange) {
  return DOM({
    tag: 'input',
    type: 'checkbox',
    style: 'bs-check',
    domaudio: domAudioPresets.defaultSelect,
    checked,
    event: ['change', (e) => onChange(e.target.checked)],
  });
}

function fillSlider(slider) {
  const min = Number(slider.min);
  const max = Number(slider.max);
  const percent = max > min ? ((Number(slider.value) - min) / (max - min)) * 100 : 0;
  slider.style.setProperty('--fill-percentage', `${2 + percent * 0.98}%`);
}

function slider({ value, min, max, steps, onInput, onChange }) {
  const step = steps > 1 ? (max - min) / (steps - 1) : 1;
  const el = DOM({
    tag: 'input',
    type: 'range',
    style: ['castle-menu-slider', 'bs-slider'],
    domaudio: domAudioPresets.defaultButton,
    min: String(min),
    max: String(max),
    step: String(step),
  });
  el.value = String(value);
  el.addEventListener('input', () => {
    fillSlider(el);
    onInput?.(Number(el.value));
  });
  el.addEventListener('change', () => onChange?.(Number(el.value)));
  requestAnimationFrame(() => fillSlider(el));
  return el;
}

function formatValue(value, fmt) {
  if (fmt === 'pct') return `${Math.round(value)}%`;
  return value.toFixed(2);
}

