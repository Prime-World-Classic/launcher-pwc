const CATEGORIES = [
  { id: 'game', label: 'bsCatGame' },
  { id: 'keys', label: 'bsCatKeys' },
  { id: 'comm', label: 'bsCatComm' },
  { id: 'chatWheel', label: 'bsCatChatWheel' },
  { id: 'pingWheel', label: 'bsCatPingWheel' },
  { id: 'advanced', label: 'bsCatAdvanced' },
];

let shownCategory = 'game';

export async function battleSettings() {
  await UserCfg.load();
  const keysLoaded = await loadKeybinds();
  NativeAPI.unregisterVoiceHotkeys?.();

  const ctx = { keysDirty: false };
  const content = DOM({ style: ['bs-content', 'wtop-list-scroll'] });
  const footer = DOM({ style: 'bs-footer' });
  const sidebar = DOM({ style: 'bs-sidebar' });
  const catButtons = new Map();

  // несохранённые клавиши «Клавиш» отбрасываются при уходе со страницы (как «Отменить» в игре)
  const discardKeys = async () => {
    if (!ctx.keysDirty) return;
    ctx.keysDirty = false;
    await loadKeybinds();
  };

  const show = async (id) => {
    if (shownCategory === 'keys' && id !== 'keys') await discardKeys();
    shownCategory = id;
    for (const [cid, el] of catButtons) el.classList.toggle('is-active', cid === id);
    content.replaceChildren();
    footer.replaceChildren();
    content.scrollTop = 0;

    let page;
    if (id === 'game') page = buildGamePage(ctx);
    else if (id === 'keys') {
      page = keysLoaded ? buildKeysPage(ctx) : DOM({ style: 'bs-note' }, Lang.text('settingsReadError'));
      if (keysLoaded) {
        footer.append(
          button(Lang.text('bsAccept'), async () => {
            if (await saveKeybinds()) ctx.keysDirty = false;
          }),
          button(Lang.text('bsCancel'), async () => {
            ctx.keysDirty = true;
            await discardKeys();
            page.refreshKeys?.();
          }),
        );
      }
    } else page = buildRowsPage(PAGES[id], ctx);
    content.append(page);
    footer.append(button(Lang.text('back'), () => root.requestClose?.(), true));
  };

  for (const cat of CATEGORIES) {
    const el = DOM(
      {
        domaudio: domAudioPresets.bigButton,
        style: ['castle-menu-item-button', 'bs-cat'],
        event: ['click', () => show(cat.id)],
      },
      Lang.text(cat.label),
    );
    catButtons.set(cat.id, el);
    sidebar.append(el);
  }

  const root = DOM(
    { id: 'wbattle-settings', style: ['wcastle-menu--quest-bg'] },
    DOM({ style: 'title-modal' }, DOM({ style: 'title-modal-text' }, Lang.text('battleSettings'))),
    DOM({ style: 'bs-body' }, sidebar, DOM({ style: 'bs-main' }, content, footer)),
  );
  if (!NativeAPI.status) root.append(DOM({ style: 'bs-warning' }, Lang.text('bsBrowserOnly')));

  root.cleanup = () => {
    if (ctx.keysDirty) loadKeybinds();
    NativeAPI.refreshVoiceHotkeys?.();
  };

  await show(CATEGORIES.some((c) => c.id === shownCategory) ? shownCategory : 'game');
  return root;
}
