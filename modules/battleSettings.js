function screenSize() {
  const ratio = window.devicePixelRatio || 1;
  return [Math.round(window.screen.width * ratio), Math.round(window.screen.height * ratio)];
}

function buildGamePage(ctx) {
  const page = DOM({ style: 'bs-page' });

  // графика: применяется кнопкой «Подтвердить», как в игре
  const current = {
    resolution: String(UserCfg.get('gfx_resolution', '')).replace(/\s/g, ''),
    quality: Math.round(UserCfg.num('common_graphics_quality', 1)),
    windowed: UserCfg.num('gfx_fullscreen', 1) === 0,
  };
  const draft = { ...current };

  // своё разрешение: от 800x600 до разрешения экрана
  const [screenW, screenH] = screenSize();
  const minW = Math.min(800, screenW);
  const minH = Math.min(600, screenH);
  const clampSize = (w, h) => [Math.min(screenW, Math.max(minW, w)), Math.min(screenH, Math.max(minH, h))];

  const modes = RESOLUTIONS.filter(([w, h]) => w <= screenW && h <= screenH).map(([w, h]) => `${w}x${h}`);
  if (!modes.includes(`${screenW}x${screenH}`)) modes.push(`${screenW}x${screenH}`);
  modes.sort((a, b) => {
    const [aw, ah] = a.split('x').map(Number);
    const [bw, bh] = b.split('x').map(Number);
    return bw - aw || bh - ah;
  });
  if (!/^\d+x\d+$/.test(current.resolution)) current.resolution = modes[0];
  draft.resolution = clampSize(...current.resolution.split('x').map(Number)).join('x');

  const accept = button(Lang.text('bsAccept'), () => applyGraphics());
  const cancel = button(Lang.text('bsCancel'), () => {
    Object.assign(draft, current);
    showResolution();
    quality.value = String(draft.quality);
    windowed.checked = draft.windowed;
    updateButtons();
  });
  const updateButtons = () => {
    const changed = draft.resolution !== current.resolution || draft.quality !== current.quality || draft.windowed !== current.windowed;
    accept.classList.toggle('is-disabled', !changed);
    cancel.classList.toggle('is-disabled', !changed);
  };
  const applyGraphics = async () => {
    const changes = { gfx_resolution: draft.resolution, gfx_fullscreen: draft.windowed ? 0 : 1 };
    if (draft.quality !== current.quality) {
      changes.common_graphics_quality = draft.quality;
      Object.assign(changes, QUALITY.find((q) => q.value === draft.quality)?.preset ?? {});
    }
    for (const [k, v] of Object.entries(changes)) changes[k] = typeof v === 'number' ? formatNumber(v) : v;
    await UserCfg.set(changes);
    Object.assign(current, draft);
    updateButtons();
    App.notify(Lang.text('bsSaved'));
  };

  const resolution = DOM({ tag: 'select', style: 'bs-select' });
  for (const mode of modes) resolution.append(DOM({ tag: 'option', value: mode }, mode.replace('x', ' x ')));
  resolution.append(DOM({ tag: 'option', value: 'custom' }, Lang.text('bsPrefResolutionCustom')));

  const sizeInput = (max) => {
    const input = DOM({ tag: 'input', style: ['bs-select', 'bs-size-input'] });
    Object.assign(input, { type: 'text', inputMode: 'numeric', maxLength: 5 });
    input.addEventListener('input', () => {
      input.value = input.value.replace(/\D/g, '');
      if (Number(input.value) > max) input.value = String(max);
    });
    input.addEventListener('change', commitCustom);
    input.addEventListener('keydown', (e) => {
      if (e.key === 'Enter') input.blur();
    });
    return input;
  };
  const customW = sizeInput(screenW);
  const customH = sizeInput(screenH);
  const customRow = DOM(
    { style: 'bs-size-row' },
    customW,
    DOM({ style: 'bs-size-sep' }, 'x'),
    customH,
    DOM({ style: 'bs-size-hint' }, `${Lang.text('bsPrefResolutionMax')} ${screenW} x ${screenH}`),
  );

  function commitCustom() {
    const [w, h] = clampSize(Number(customW.value) || screenW, Number(customH.value) || screenH);
    customW.value = String(w);
    customH.value = String(h);
    draft.resolution = `${w}x${h}`;
    updateButtons();
  }
  function showResolution(forceCustom = false) {
    const custom = forceCustom || !modes.includes(draft.resolution);
    resolution.value = custom ? 'custom' : draft.resolution;
    const [w, h] = draft.resolution.split('x');
    customW.value = w;
    customH.value = h;
    customRow.style.display = custom ? '' : 'none';
  }
  showResolution();
  resolution.addEventListener('change', () => {
    if (resolution.value === 'custom') {
      showResolution(true);
      customW.focus();
      return;
    }
    draft.resolution = resolution.value;
    showResolution();
    updateButtons();
  });

  const quality = DOM({ tag: 'select', style: 'bs-select' });
  for (const q of QUALITY) quality.append(DOM({ tag: 'option', value: String(q.value) }, Lang.text(q.label)));
  quality.value = String(draft.quality);
  quality.addEventListener('change', () => {
    draft.quality = Number(quality.value);
    updateButtons();
  });

  const windowed = checkbox(draft.windowed, (checked) => {
    draft.windowed = checked;
    updateButtons();
  });
  const windowedLabel = DOM({ tag: 'label', style: 'bs-row-label' }, Lang.text('bsPrefWindowMode'));
  windowedLabel.addEventListener('click', () => windowed.click());

  page.append(
    header('bsPrefGraphics'),
    DOM(
      { style: 'bs-grid' },
      DOM({ style: 'bs-field' }, DOM({ style: 'bs-field-label' }, Lang.text('bsPrefResolution')), resolution, customRow),
      DOM({ style: 'bs-field' }, DOM({ style: 'bs-field-label' }, Lang.text('bsPrefGraphicQuality')), quality),
    ),
    DOM({ style: ['bs-row', 'bs-row--check'] }, windowed, windowedLabel),
    DOM({ style: 'bs-buttons' }, accept, cancel),
  );
  updateButtons();

  // частота кадров: сохраняется сразу, игра читает её при запуске боя
  const frameRate = buildRowsPage(
    [
      { type: 'header', label: 'bsPrefFrameRate' },
      { type: 'check', id: 'vsync', variable: 'gfx_vsync', def: 1, label: 'bsPrefVsync' },
      { type: 'note', label: 'bsPrefVsyncNote' },
      { type: 'check', id: 'gpuSyncLag', variable: 'gfx_gpu_sync_lag', def: 0, label: 'bsPrefGpuSyncLag' },
      { type: 'note', label: 'bsPrefGpuSyncLagNote' },
    ],
    ctx,
  );
  page.append(...frameRate.childNodes);

  // звук: применяется сразу, как ползунки в игре (0..1, ping_sound_volume — 0..100)
  const volume = (label, variable, def, max = 1, steps = 100, enabled = true) => {
    const value = Math.min(max, Math.max(0, UserCfg.num(variable, def)));
    const text = DOM({ style: 'bs-value' }, `${Math.round((value / max) * 100)}%`);
    const el = slider({
      value,
      min: 0,
      max,
      steps,
      onInput: (v) => {
        text.textContent = `${Math.round((v / max) * 100)}%`;
      },
      onChange: (v) => UserCfg.set({ [variable]: formatNumber(v) }),
    });
    el.disabled = !enabled;
    const field = DOM({ style: enabled ? 'bs-field' : ['bs-field', 'is-disabled'] }, DOM({ style: 'bs-field-label' }, Lang.text(label)), DOM({ style: 'bs-slider-box' }, el, text));
    return field;
  };
  page.append(
    header('bsPrefSound'),
    DOM(
      { style: 'bs-grid' },
      volume('bsPrefMusicVolume', 'music_volume', 0.8),
      volume('bsPrefVoiceVolume', 'voice_volume', 0.8),
      volume('bsPrefSoundVolume', 'sound_volume', 0.8),
      volume('bsAdvPingSoundVolume', 'ping_sound_volume', 70, 100, 11, UserCfg.num('ping_sound', 1) !== 0),
    ),
  );
  return page;
}

// ---------------------------------------------------------------- страница «Клавиши»

function buildKeysPage(ctx) {
  const page = DOM({ style: 'bs-page' });
  const inputs = [];
  for (const group of KEY_GROUPS) {
    page.append(header(group.title));
    for (const r of group.rows) {
      const input = bindKeyInput(r.command, r.value ?? null, () => {
        ctx.keysDirty = true;
        inputs.forEach((i) => i.refresh());
      });
      inputs.push(input);
      page.append(row(Lang.text(r.label), input));
    }
  }
  page.refreshKeys = () => inputs.forEach((i) => i.refresh());
  return page;
}

