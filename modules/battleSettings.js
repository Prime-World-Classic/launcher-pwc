// "a,b,c" -> слоты колеса, как ParseWheelItems в игре: только известные id, без повторов, не больше 8, не меньше 4
function parseWheelItems(text, valid) {
  const items = [];
  for (const part of String(text).split(',')) {
    if (!/^\s*\d+\s*$/.test(part)) continue;
    const value = parseInt(part, 10);
    if (valid.includes(value) && !items.includes(value) && items.length < WHEEL_MAX) items.push(value);
  }
  for (const id of valid) {
    if (items.length >= WHEEL_MIN) break;
    if (!items.includes(id)) items.push(id);
  }
  return items;
}

