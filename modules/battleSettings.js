const USER_CFG_HEADER = [
  '//============================================================================',
  '// generated by the game, please do not modify',
  '//============================================================================',
];

export const UserCfg = {
  path: null,
  lines: [],
  eol: '\r\n',
  values: new Map(),

  async load() {
    this.values.clear();
    this.lines = [...USER_CFG_HEADER];
    this.path = null;
    if (!NativeAPI.status) return;
    const documents = NativeAPI.getDocumentsDir();
    if (!documents) return;
    this.path = NativeAPI.path.join(documents, 'My Games', 'Prime World Classic', 'user.cfg');
    let text = '';
    try {
      text = await NativeAPI.fileSystem.promises.readFile(this.path, 'utf8');
    } catch {
      return; // нет файла — игра ещё не запускалась: значения по умолчанию, файл создастся при первой записи
    }
    this.eol = text.includes('\r\n') ? '\r\n' : '\n';
    this.lines = text.split(/\r?\n/);
    while (this.lines.length && this.lines[this.lines.length - 1] === '') this.lines.pop();
    for (const line of this.lines) {
      const m = /^\s*setvar\s+(\S+)\s*=\s*(.*?)\s*$/.exec(line);
      if (m) this.values.set(m[1], m[2]);
    }
  },

  get(name, def) {
    return this.values.has(name) ? this.values.get(name) : def;
  },

  num(name, def) {
    const v = parseFloat(this.get(name, ''));
    return Number.isFinite(v) ? v : def;
  },

  // changes: { name: value }; строки setvar меняются на месте, новые встают по алфавиту (как пишет игра)
  async set(changes) {
    for (const [name, raw] of Object.entries(changes)) {
      const value = String(raw);
      this.values.set(name, value);
      const line = `setvar ${name} = ${value}`;
      const index = this.lines.findIndex((l) => new RegExp(`^\\s*setvar\\s+${name}\\s*=`).test(l));
      if (index >= 0) {
        this.lines[index] = line;
        continue;
      }
      let at = this.lines.length;
      for (let i = 0; i < this.lines.length; i++) {
        const m = /^\s*setvar\s+(\S+)/.exec(this.lines[i]);
        if (m && m[1] > name) {
          at = i;
          break;
        }
      }
      this.lines.splice(at, 0, line);
    }
    if (!this.path) return;
    try {
      await NativeAPI.fileSystem.promises.mkdir(NativeAPI.path.dirname(this.path), { recursive: true });
      await NativeAPI.fileSystem.promises.writeFile(this.path, this.lines.join(this.eol) + this.eol, 'utf8');
    } catch (e) {
      console.error('battleSettings: user.cfg write failed', e);
      App.error(Lang.text('bsSaveError'));
    }
  },
};

function formatNumber(value) {
  return String(Math.round(value * 1000000) / 1000000);
}

