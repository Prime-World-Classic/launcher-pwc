function buildRowsPage(rowsDesc, ctx) {
  const page = DOM({ style: 'bs-page' });
  const checks = new Map(); // id -> текущее значение галочки
  const dependents = []; // { dep, element, controls }

  // dep: id галочки, от которой зависит строка; '!id' — строка доступна, пока галочка выключена
  const updateEnabled = () => {
    for (const d of dependents) {
      const inverted = d.dep.startsWith('!');
      const checked = checks.get(inverted ? d.dep.slice(1) : d.dep);
      const enabled = inverted ? checked !== true : checked !== false;
      d.element.classList.toggle('is-disabled', !enabled);
      for (const c of d.controls) c.disabled = !enabled;
    }
  };

  for (const desc of rowsDesc) {
    switch (desc.type) {
      case 'header':
        page.append(header(desc.label));
        break;
      case 'note':
        page.append(DOM({ style: 'bs-note' }, Lang.text(desc.label)));
        break;
      case 'check': {
        const value = UserCfg.num(desc.variable, desc.def) !== 0;
        checks.set(desc.id, value);
        const box = checkbox(value, async (checked) => {
          checks.set(desc.id, checked);
          updateEnabled();
          await UserCfg.set({ [desc.variable]: checked ? 1 : 0 });
        });
        const label = DOM({ tag: 'label', style: 'bs-row-label' }, Lang.text(desc.label));
        label.addEventListener('click', () => {
          if (!box.disabled) box.click();
        });
        const element = DOM({ style: ['bs-row', 'bs-row--check'] }, box, label);
        page.append(element);
        if (desc.dep) dependents.push({ dep: desc.dep, element, controls: [box] });
        break;
      }
      case 'slider': {
        const value = Math.min(desc.max, Math.max(desc.min, UserCfg.num(desc.variable, desc.def)));
        const text = DOM({ style: 'bs-value' }, formatValue(value, desc.fmt));
        const el = slider({
          value,
          min: desc.min,
          max: desc.max,
          steps: desc.steps,
          onInput: (v) => {
            text.textContent = formatValue(v, desc.fmt);
          },
          onChange: (v) => UserCfg.set({ [desc.variable]: formatNumber(v) }),
        });
        const element = row(Lang.text(desc.label), DOM({ style: 'bs-slider-box' }, el, text));
        page.append(element);
        if (desc.dep) dependents.push({ dep: desc.dep, element, controls: [el] });
        break;
      }
      case 'number': {
        // целое число; пусто или 0 — выключено (desc.offLabel), иначе от desc.min до desc.max
        let current = Math.max(0, Math.round(UserCfg.num(desc.variable, desc.def)));
        if (current > 0) current = Math.min(desc.max, Math.max(desc.min, current)); // как ползунок в игре
        const input = DOM({ tag: 'input', style: ['bs-select', 'bs-number-input'] });
        Object.assign(input, { type: 'text', inputMode: 'numeric', maxLength: String(desc.max).length, placeholder: Lang.text(desc.offLabel) });
        const show = (v) => {
          input.value = v > 0 ? String(v) : '';
        };
        show(current);
        input.addEventListener('input', () => {
          input.value = input.value.replace(/\D/g, '');
        });
        input.addEventListener('change', async () => {
          let v = Number(input.value) || 0;
          if (v > 0) v = Math.min(desc.max, Math.max(desc.min, v));
          show(v);
          if (v === current) return;
          current = v;
          await UserCfg.set({ [desc.variable]: v });
        });
        input.addEventListener('keydown', (e) => {
          if (e.key === 'Enter') input.blur();
        });
        const element = row(Lang.text(desc.label), DOM({ style: 'bs-slider-box' }, input, DOM({ style: 'bs-value' }, desc.unit ?? '')));
        page.append(element);
        if (desc.dep) dependents.push({ dep: desc.dep, element, controls: [input] });
        break;
      }
      case 'key':
        // как в игре: клавиша этой страницы применяется сразу
        page.append(row(Lang.text(desc.label), bindKeyInput(desc.command, null, () => saveKeybinds())));
        break;
      case 'launcherKey':
        page.append(row(Lang.text(desc.label), voiceHotkeyInput(desc.settingKey, 'bs-key', { allowMouse: Boolean(desc.allowMouse) })));
        break;
      case 'launcherMic': {
        // микрофон голосовой связи лаунчера (тот же выбор — в «Настройках замка»)
        const mic = voiceMicControls();
        page.append(row(Lang.text('voiceMic'), mic.select), row(Lang.text('voiceMicCheck'), mic.test));
        break;
      }
      case 'launcherCheck': {
        // настройка лончера (launcher.cfg), а не user.cfg: сохраняется сразу, как launcherKey
        const box = checkbox(Settings.settings[desc.settingKey] === desc.on, async (checked) => {
          Settings.settings[desc.settingKey] = checked ? desc.on : desc.off;
          await Settings.WriteSettings();
        });
        const label = DOM({ tag: 'label', style: 'bs-row-label' }, Lang.text(desc.label));
        label.addEventListener('click', () => {
          if (!box.disabled) box.click();
        });
        const element = DOM({ style: ['bs-row', 'bs-row--check'] }, box, label);
        page.append(element);
        if (desc.dep) dependents.push({ dep: desc.dep, element, controls: [box] });
        break;
      }
      case 'wheel':
        page.append(buildWheelEditor(WHEELS[desc.wheel]));
        break;
    }
  }
  updateEnabled();
  return page;
}

// ---------------------------------------------------------------- редактор колеса

function buildWheelEditor(wheel) {
  let items = parseWheelItems(UserCfg.get(wheel.variable, wheel.def), wheel.ids);
  let selected = 0;
  const root = DOM({ style: 'bs-wheel-editor' });
  const save = () => UserCfg.set({ [wheel.variable]: items.join(',') });

  // команда уже в другом слоте — меняется местами с той, что в целевом (PutIntoSlot)
  const putIntoSlot = (id, slot) => {
    if (slot < 0 || slot >= items.length) return;
    const old = items.indexOf(id);
    if (old === slot) return;
    if (old >= 0) items[old] = items[slot];
    items[slot] = id;
    save();
  };
  const swapSlots = (a, b) => {
    if (a === b || a < 0 || b < 0 || a >= items.length || b >= items.length) return;
    [items[a], items[b]] = [items[b], items[a]];
    save();
  };
  const onDrop = (e, slot) => {
    e.preventDefault();
    let source = null;
    try {
      source = JSON.parse(e.dataTransfer.getData('text/plain'));
    } catch {
      return;
    }
    if (source?.slot !== undefined) swapSlots(source.slot, slot);
    else if (source?.catalog !== undefined) putIntoSlot(source.catalog, slot);
    selected = slot;
    render();
  };
  const dragSource = (el, data) => {
    el.draggable = true;
    el.addEventListener('dragstart', (e) => {
      e.dataTransfer.setData('text/plain', JSON.stringify(data));
      e.dataTransfer.effectAllowed = 'move';
    });
  };
  // SVG-секторы HTML-перетаскивание не поддерживают: сектор тянется мышью, цель — сектор или
  // строка слота под курсором (data-wheel-slot), как в бою
  const sectorDrag = (el, slot) => {
    el.addEventListener('mousedown', (down) => {
      if (down.button !== 0) return;
      let moved = false;
      let target = null;
      const targetAt = (e) => document.elementFromPoint(e.clientX, e.clientY)?.closest?.('[data-wheel-slot]') ?? null;
      const onMove = (e) => {
        if (!moved && Math.hypot(e.clientX - down.clientX, e.clientY - down.clientY) < 4) return;
        moved = true;
        const next = targetAt(e);
        if (next === target) return;
        target?.classList.remove('is-drop');
        target = next;
        target?.classList.add('is-drop');
      };
      const onUp = (e) => {
        document.removeEventListener('mousemove', onMove);
        document.removeEventListener('mouseup', onUp);
        target?.classList.remove('is-drop');
        if (!moved) return; // щелчок — выбор слота (click)
        const to = targetAt(e);
        if (!to) return;
        const slotTo = Number(to.getAttribute('data-wheel-slot'));
        swapSlots(slot, slotTo);
        selected = slotTo;
        render();
      };
      document.addEventListener('mousemove', onMove);
      document.addEventListener('mouseup', onUp);
    });
  };
  const dropTarget = (el, slot) => {
    el.addEventListener('dragover', (e) => {
      e.preventDefault();
      el.classList.add('is-drop');
    });
    el.addEventListener('dragleave', () => el.classList.remove('is-drop'));
    el.addEventListener('drop', (e) => {
      el.classList.remove('is-drop');
      onDrop(e, slot);
    });
  };

  const render = () => {
    root.replaceChildren();
    root.append(header('bsWheelSlots'), DOM({ style: 'bs-note' }, Lang.text('bsWheelHint')));

    // превью колеса: сектор 0 сверху, по часовой стрелке (как колесо в бою)
    const n = items.length;
    const ns = 'http://www.w3.org/2000/svg';
    const svg = document.createElementNS(ns, 'svg');
    svg.setAttribute('viewBox', '-100 -100 200 200');
    svg.classList.add('bs-wheel');
    const rOut = 96;
    const rIn = 30;
    const point = (r, deg) => {
      const a = ((deg - 90) * Math.PI) / 180;
      return `${(r * Math.cos(a)).toFixed(2)} ${(r * Math.sin(a)).toFixed(2)}`;
    };
    const sector = 360 / n;
    for (let i = 0; i < n; i++) {
      const a0 = i * sector - sector / 2;
      const a1 = a0 + sector;
      const path = document.createElementNS(ns, 'path');
      path.setAttribute('d', `M ${point(rIn, a0)} L ${point(rOut, a0)} A ${rOut} ${rOut} 0 0 1 ${point(rOut, a1)} L ${point(rIn, a1)} A ${rIn} ${rIn} 0 0 0 ${point(rIn, a0)} Z`);
      path.classList.add('bs-wheel-sector');
      if (i === selected) path.classList.add('is-selected');
      path.addEventListener('click', () => {
        selected = i;
        render();
      });
      path.setAttribute('data-wheel-slot', String(i));
      sectorDrag(path, i);
      dropTarget(path, i);
      svg.append(path);

      const mid = point((rOut + rIn) / 2 + 4, i * sector);
      const [x, y] = mid.split(' ').map(Number);
      if (wheel.icon) {
        const img = document.createElementNS(ns, 'image');
        img.setAttribute('href', wheel.icon(items[i]));
        img.setAttribute('x', String(x - 15));
        img.setAttribute('y', String(y - 15));
        img.setAttribute('width', '30');
        img.setAttribute('height', '30');
        img.style.pointerEvents = 'none';
        svg.append(img);
      } else {
        const t = document.createElementNS(ns, 'text');
        t.setAttribute('x', String(x));
        t.setAttribute('y', String(y));
        t.setAttribute('text-anchor', 'middle');
        t.setAttribute('dominant-baseline', 'central');
        t.classList.add('bs-wheel-number');
        t.textContent = String(i + 1);
        svg.append(t);
      }
    }
    const hub = document.createElementNS(ns, 'circle');
    hub.setAttribute('r', String(rIn - 4));
    hub.classList.add('bs-wheel-hub');
    svg.append(hub);

    // список слотов
    const slots = DOM({ style: 'bs-wheel-slots' });
    items.forEach((id, i) => {
      const value = DOM({ style: i === selected ? ['bs-wheel-slot', 'is-selected'] : 'bs-wheel-slot' });
      if (wheel.icon) value.append(DOM({ tag: 'img', src: wheel.icon(id), style: 'bs-wheel-icon', draggable: false }));
      value.append(wheel.label(id));
      value.addEventListener('click', () => {
        selected = i;
        render();
      });
      value.setAttribute('data-wheel-slot', String(i));
      dragSource(value, { slot: i });
      dropTarget(value, i);
      slots.append(DOM({ style: 'bs-wheel-slot-row' }, DOM({ style: 'bs-wheel-slot-num' }, String(i + 1)), value));
    });
    const minus = button('-', () => {
      if (items.length <= WHEEL_MIN) return;
      items.pop();
      selected = Math.min(selected, items.length - 1);
      save();
      render();
    });
    const plus = button('+', () => {
      if (items.length >= WHEEL_MAX) return;
      const free = wheel.ids.find((id) => !items.includes(id));
      if (free === undefined) return;
      items.push(free);
      selected = items.length - 1;
      save();
      render();
    });
    minus.classList.add('bs-wheel-count-btn');
    plus.classList.add('bs-wheel-count-btn');
    minus.title = minus.textContent;
    plus.title = plus.textContent;
    minus.setAttribute('aria-label', minus.textContent);
    plus.setAttribute('aria-label', plus.textContent);
    minus.replaceChildren(DOM({ tag: 'img', src: 'content/icons/remove.png', alt: '', style: 'bs-wheel-count-icon' }));
    plus.replaceChildren(DOM({ tag: 'img', src: 'content/icons/add.png', alt: '', style: 'bs-wheel-count-icon' }));
    minus.classList.toggle('is-disabled', items.length <= WHEEL_MIN);
    plus.classList.toggle('is-disabled', items.length >= WHEEL_MAX);
    slots.append(DOM({ style: 'bs-wheel-count' }, minus, DOM({}, `${Lang.text('bsWheelCount')}: ${items.length}`), plus));

    // каталог команд: щелчок — в выбранный слот, выбор переходит к следующему
    const catalog = DOM({ style: 'bs-wheel-catalog' });
    for (const id of wheel.ids) {
      const el = DOM({ style: items.includes(id) ? ['bs-wheel-item', 'is-used'] : 'bs-wheel-item' });
      if (wheel.icon) el.append(DOM({ tag: 'img', src: wheel.icon(id), style: 'bs-wheel-icon', draggable: false }));
      el.append(wheel.label(id));
      el.addEventListener('click', () => {
        putIntoSlot(id, selected);
        if (selected < items.length - 1) selected++;
        render();
      });
      dragSource(el, { catalog: id });
      catalog.append(el);
    }

    root.append(DOM({ style: 'bs-wheel-top' }, svg, slots), catalog);
  };

  render();
  return root;
}

